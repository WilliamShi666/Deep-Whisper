/** 按 id 取皮肤；'default'/null/未知 id 均返回 undefined（即无背景） */
export function getChatTheme(id: string | null | undefined): ChatTheme | undefined {
  if (!id || id === DEFAULT_CHAT_THEME_ID) return undefined;
  return CHAT_THEMES.find((t) => t.id === id);
}

/** 按伴侣性别过滤可选皮肤池 */
export function getChatThemesForGender(gender: 'male' | 'female'): ChatTheme[] {
  return CHAT_THEMES.filter((t) => t.gender === gender);
}

/* ==================== UI 色调（界面配色方案） ==================== */

/**
 * UI 色调：聊天界面的整体配色，与背景皮肤解耦，可自由叠加。
 * 每个色调含 dark / light 两种模式；CSS 变量定义在 globals.css
 * 的 html[data-ui-theme='<id>'] 作用域块中（specificity 高于 .dark，可覆盖全局暗色）。
 *
 * scrim：叠加在背景图上的遮罩基调色。深色 UI 用极深夜色，浅色 UI 用奶白色，
 * 保证「界面色调」与「背景图」融合统一。
 */
export interface UiTheme {
  id: string;
  name: string;
  /** 英文名（诗意重命名，用户 2026-10-03 选定）；与中文 `name` 并存，中文态不变。 */
  nameEn: string;
  mode: 'dark' | 'light';
  /** 面板预览底色 */
  swatch: string;
  /** 面板预览点缀色 */
  accent: string;
  /** 背景图遮罩基调色（深色 UI = 深夜色，浅色 UI = 奶白色） */
  scrim: string;
}

