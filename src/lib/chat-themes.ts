/**
 * 聊天皮肤系统 —— 预生成二次元背景图库。
 *
 * 皮肤 = 聊天窗口背景图 + 深色遮罩，只作用于聊天窗口；
 * 气泡色仍随角色走（characters.ts 的 theme），两者解耦。
 *
 * 性别约束：theme.gender 表示「画面人物性别 = 适用的伴侣性别」。
 * 可选皮肤池按当前伴侣的性别动态过滤（运行时从角色定义查 gender，
 * 见 resolve-gender.ts），不写死任何角色名单，新增角色自动适配。
 *
 * 背景图为预生成 DeepSeek 原创素材（public/backgrounds/deepseek/）；
 * 每张图单独声明亮度与移动/桌面裁切点。
 */

export interface ChatTheme {
  id: string;
  name: string;
  /**
   * 英文名（**诗意重命名**，用户 2026-10-03 选定）：与中文 `name` 并存，中文态逐字符不变。
   * 与中文原名意象对齐，不是描述性直译。
   */
  nameEn: string;
  /** 氛围一句话（选择面板副标题） */
  desc: string;
  /** 英文副标题；保留 `FQxx · ` / `MQxx · ` 前缀与 `·` 分隔符（前缀与 id 的编号逐字符对应）。 */
  descEn: string;
  /** 画面人物性别 = 适用伴侣性别 */
  gender: 'male' | 'female';
  /** 背景图路径 */
  image: string;
  /** 横屏专用图；手机仍使用原始竖版图 */
  desktopImage?: string;
  /** 选择面板缩略图；未提供时回退 image */
  thumbnail?: string;
  /** 遮罩基调色（渐变遮罩，保证气泡可读性） */
  scrim: string;
  /** 素材级滤镜 */
  brightness?: number;
  saturation?: number;
  /** object-position：窄屏侧重横向裁切，桌面宽屏侧重纵向裁切 */
  mobilePosition?: string;
  desktopPosition?: string;
}

